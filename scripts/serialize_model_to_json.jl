# Serialize the B2DxDK amplitude model to the amplitude-serialization format:
#   data/b2dxdk_amplitude_model_Cminus.json   (19 chains)
#   data/b2dxdk_amplitude_model_Cplus.json    (15 chains, X(2900) absent)
#   data/b2dxdk_amplitude_model.json          (copy of Cminus)
#   data/resonances/*.json                    (one file per resonance, Cminus)
#   data/b2dxdk_amplitude_model_notes.md      (what is folded into the weights; not part of the JSON)
#
# Every file is read back with CascadeDecaysIO alone (no B2DxDK lineshape types) and
# checked against the B2DxDK model on the 100 cross-check events and its checksums.
# The three validation points of each file are generated by CascadeDecaysIO for that
# model (D* on its mass, intensity at least 0.1 x the mean of 1000 such events).
#
# Run from the repo root:  julia --project=. scripts/serialize_model_to_json.jl
using Arrow
using B2DxDK
using CascadeDecays
using CascadeDecaysIO
using DataFrames
using Printf

const M = B2DxDK
# final states 1..4 and the initial state, per TF-PWA charge configuration `c`
const PARTICLE_LABELS = Dict(
    :Cminus => ("D0", "pi+", "D-", "K+", "B+"),        # c = -1: B+ -> D*+ D- K+, D*+ -> D0 pi+
    :Cplus => ("anti-D0", "pi-", "D+", "K+", "B+"),    # c = +1: B+ -> D*- D+ K+, D*- -> anti-D0 pi-
)
const MASSES = SystemMasses(
    M.nominal_mass["D0"], M.nominal_mass["pi"], M.nominal_mass["D"], M.nominal_mass["K"];
    m0 = M.nominal_mass["Bp"],
)
const DISTRIBUTION = Dict(
    :Cminus => "Bplus_to_D0_piplus_Dminus_Kplus_Cminus",
    :Cplus => "Bplus_to_antiD0_piminus_Dplus_Kplus_Cplus",
)
const RTOL = 1e-10

# Validation points, nodes of the reference topology (((1, 2), 3), 4): m(D0 pi) = m(D*)
# (TF-PWA fixes the D* mass), point 2 within 10 MeV above the D* D threshold (X(3872))
const DSTAR_ON_SHELL = Dict((1, 2) => M.nominal_mass["Dst"])
const NEAR_THRESHOLD = (M.nominal_mass["Dst"] + M.nominal_mass["D"]) .+ (0.0, 0.010)
const VALIDATION_NODE_MASSES = [
    DSTAR_ON_SHELL,
    merge(DSTAR_ON_SHELL, Dict(((1, 2), 3) => NEAR_THRESHOLD)),
    DSTAR_ON_SHELL,
]

# ---------------------------------------------------------------------------
# Writing
# ---------------------------------------------------------------------------
function write_model(path, cascade; name, charge = :Cminus)
    validation = validationSection(cascade, MASSES; distribution = name, node_masses = VALIDATION_NODE_MASSES)
    document = amplitudeSerializationDict(cascade, MASSES;
        particle_labels = PARTICLE_LABELS[charge], name, validation)
    writeJson(path, document)
    return path
end

# ---------------------------------------------------------------------------
# Verification of a written file with CascadeDecaysIO alone
# ---------------------------------------------------------------------------
const CROSSCHECK = DataFrame(Arrow.Table(joinpath(M.data_dir, "crosscheck.arrow")))
const CROSSCHECK_POINTS = [event_point(row) for row in eachrow(CROSSCHECK)]

const ANALYSIS_TYPES = Union{M.TFPWAMultichannelBreitWigner, M.NRExpLineshape, M.DstarDeltaLineshape}
unwrap(f) = f isa NamedLineshape ? f.lineshape : f

function verify(path, cascade)
    read_cascade, _, document = readJson(path)
    any(ch -> any(p -> unwrap(p) isa ANALYSIS_TYPES, ch.propagators), read_cascade.chains) &&
        error("$path: read back with B2DxDK lineshape types")
    max_rel = maximum(CROSSCHECK_POINTS) do point
        a = only(amplitude(cascade, point))
        b = only(amplitude(read_cascade, point))
        abs(a - b) / max(abs(a), floatmin(Float64))
    end
    checks = validate(document, read_cascade)
    ok = max_rel <= RTOL && all(r -> r.passed, checks)
    @printf("  %-34s %2d chains  max rel |dA| = %.1e  checksums %d/%d  %s\n",
        basename(path), length(read_cascade.chains), max_rel,
        count(r -> r.passed, checks), length(checks), ok ? "ok" : "FAILED")
    ok || error("verification failed for $path")
    return read_cascade
end

# total amplitude of the C- model against the TF-PWA-aligned reference file
function compare_with_reference(read_cascade)
    lines = readlines(joinpath(M.data_dir, "crosscheck_amplitudes_reference.txt"))
    reference = [parse.(Float64, split(line, '\t')) for line in lines[2:end]]
    max_abs = maximum(eachindex(CROSSCHECK_POINTS)) do i
        total = only(amplitude(read_cascade, CROSSCHECK_POINTS[i]))
        abs(total - complex(reference[i][end - 1], reference[i][end]))
    end
    @printf("  C- model from JSON vs crosscheck_amplitudes_reference.txt: max |dA| = %.1e\n", max_abs)
    max_abs <= RTOL || error("C- JSON does not reproduce the reference amplitudes")
end

# ---------------------------------------------------------------------------
# Companion notes: everything folded into the weights (not part of the JSON)
# ---------------------------------------------------------------------------
fmt_complex(z) = @sprintf("%.6g %s %.6gi", real(z), imag(z) < 0 ? "-" : "+", abs(imag(z)))

function write_notes(path)
    rows = M.resonance_chains_df
    open(path, "w") do io
        println(io, """
        # B2DxDK amplitude-serialization files: notes

        Generated by `scripts/serialize_model_to_json.jl`. The JSON files define the amplitude
        and its domain completely; this file documents conventions and the provenance of the
        numbers. It is not read by any program.

        ## Files

        | file | decay (TF-PWA `c`) | final state 1, 2, 3, 4 | chains |
        |---|---|---|---|
        | `b2dxdk_amplitude_model_Cminus.json` | B+ -> D*+ D- K+, D*+ -> D0 pi+ (c = -1) | D0, pi+, D-, K+ | 19 |
        | `b2dxdk_amplitude_model_Cplus.json` | B+ -> D*- D+ K+, D*- -> anti-D0 pi- (c = +1) | anti-D0, pi-, D+, K+ | 15 |
        | `b2dxdk_amplitude_model.json` | copy of the Cminus file | | |
        | `resonances/*.json` | one resonance each, Cminus | D0, pi+, D-, K+ | 1-3 |

        Chain names are `<resonance>_l<l of the production vertex>_l<l of the resonance decay>`.
        Resonance names are those of the TF-PWA configuration ("." stands for "+"):

        | TF-PWA name | published name |
        |---|---|
        | X(3872) | EFF(1++) (label of the TF-PWA analysis notebook for the 1++ component at the D* D threshold) |
        | X(3915)(0-) | eta_c(3945) |
        | chi(c2)(3930) | chi_c2(3930) |
        | X(3940)(1.) | h_c(4000) |
        | X(3993) | chi_c1(4010) |
        | Psi(4040) | psi(4040) |
        | X(4300) | h_c(4300) |
        | NR(0-)SPp, NR(1.)PSp, NR(0-)SPm, NR(1-)PPm | NR(0-+), NR(1++), NR(0--), NR(1--) |
        | X0(2900), X1(2900) | T*_cs0(2870), T*_cs1(2900) |

        ## Charge configurations and B-

        - The two configurations are one model: in the TF-PWA fit both enter one likelihood with
          the same parameters, and the probability density is the intensity of the respective
          file divided by the sum of both phase-space integrals. Components with TF-PWA `C(...)`,
          `C: 1` change sign between the files; X(2900) exists only in Cminus (D+ K+ is doubly
          charged).
        - B- candidates: TF-PWA (`cp_trans`, default true) evaluates them with the same amplitude
          after a parity transformation of the three-momenta (p -> -p), i.e. the model is
          CP-symmetric. Use the charge-conjugate final state and flip the three-momenta.

        ## D*

        TF-PWA fixes the D* mass (`model: one`, narrow-width approximation). The JSON encodes this
        as the lineshape `lineshape_Dst` = exp(-((sqrt(sigma) - m)/w)^$(M.DSTAR_DELTA_ORDER) / 2) with
        m = $(M.nominal_mass["Dst"]) GeV and w = $(M.DSTAR_DELTA_WIDTH) GeV: a flat-top delta distribution
        in m(D0 pi) with value 1 at m. Integrals over the full four-body `phase_space` domain reproduce
        the fixed-mass ones up to O(w^2) (relative deviation of fit fractions < 1e-9). Within
        |m(D0 pi) - m| < 3e-7 GeV the D* factor is 1 to better than 1e-8; the rest of the amplitude
        keeps its genuine m(D0 pi) dependence (as with a constant D* lineshape). The profile is zero
        for |m(D0 pi) - m| > 1.5e-6 GeV: input four-vectors must have m(D0 pi) = m(D*) = 2.01026 GeV
        (D* mass constraint with this value, double precision, preferably in the B rest frame).
        Events for integration or toys have to be drawn with m(D0 pi) on this profile (in practice
        m(D0 pi) = m(D*)); uniform sampling of the 4-body phase space almost never hits it. The D* -> D0 pi vertex is a P-wave (l = 1, s = 0) without form factor
        (TF-PWA `has_barrier_factor: False`), which is exact on the delta.

        ## Validation points

        The three points of each file are generated for its model with
        `CascadeDecaysIO.validationSection(cascade, masses; node_masses)`: successive isotropic
        two-body decays along the reference topology with m(D0 pi) = m(D*), point 2 with
        m(D* D) within 10 MeV above the D* D threshold. A point is kept if the intensity of the
        model there is at least 0.1 times its mean over 1000 events drawn the same way.

        ## Precision

        - JSON read with CascadeDecaysIO vs the B2DxDK model: <= 2e-15 relative per event.
        - JSON (Cminus) vs `crosscheck_amplitudes_reference.txt`: <= 2.2e-14 absolute (100 events).
        - JSON vs TF-PWA itself at the validation points: <= 2e-9 relative in |A|^2. The
          non-resonant chains differ from current TF-PWA by a constant factor of 1 - 4e-10
          (l = 1 decays) and 1 - 8e-10 (NR(1-)PPm); the cause is not identified.

        ## Amplitude conventions

        The amplitude is evaluated recursively from the root of each chain. For a node X -> A B
        (A = first, B = second entry of the node), in the helicity frame of X, with (theta, phi)
        the polar angles of A:

            A_X(lX) = sum_{lA, lB} conj(D^{jX}_{lX, lA-lB}(phi, theta, 0)) * H_{lA lB} * (-1)^(jB - lB)
                      * F(mX^2, mA^2, mB^2) * A_A(lA) * A_B(lB)
            H_{lA lB} = sqrt((2l+1)/(2jX+1)) <jA lA; jB -lB | s, lA-lB> <l 0; s, lA-lB | jX, lA-lB>

        - Frame of A: rotate by R_z(-phi), then R_y(-theta), then boost along z into the rest frame
          of A. Frame of B: the same rotations followed by a rotation by pi about y, then the boost
          (Jacob-Wick convention for particle 2, with the phase (-1)^(jB - lB) above).
        - Every internal line X contributes its lineshape at sigma = mX^2 and n_X = sqrt(2 jX + 1).
        - The total amplitude is the sum of weight x chain amplitude. All external spins are 0, so
          no Wigner rotations to the reference topology occur.
        - Lineshapes `lineshape_X(3872)`, `X(3940)(1.)`, `X(3993)`, `X(4300)`: TF-PWA `BWR_LS` with
          its default `fix_bug1 = false` (width term carries m/m0), written as `generic_function`.
        - `lineshape_NR(0-)SPp`: exp(-(alpha + i beta)(sigma - m0^2)), written as `generic_function`.
        - Form factors are unnormalized Blatt-Weisskopf factors (radius $(M.WELL_SIZE) GeV^-1); TF-PWA's
          normalization 1/F_l(q0) is part of the weight.
        - Signs in the weights: TF-PWA `C(...)` wrappers with `C: 1` give -1 in Cminus (+1 in Cplus);
          X1(2900) carries -1 because TF-PWA omits the Jacob-Wick particle-2 convention, which for
          these chains reduces to this constant.

        ## Weight decomposition (C-)

        weight = TF-PWA coupling x sign x 1/F(q0) production x 1/F(q0) decay x gamma split x spin norm

        | chain | TF-PWA parameters | TF-PWA coupling | sign C- | sign C+ | 1/F(q0) prod. | 1/F(q0) decay | gamma | spin norm | weight C- |
        |---|---|---|---|---|---|---|---|---|---|""")
        for row in eachrow(rows)
            name = row.resonance_name
            m_r = M.nominal_mass[name]
            prod_norm, dec_norm = if row.topology == :DxD
                (M.nominal_vertex_matching_factor(M.vertex_l(row.root_two_ls), M.WELL_SIZE, M.nominal_mass["Bp"], m_r, M.nominal_mass["K"]),
                 M.nominal_vertex_matching_factor(M.vertex_l(row.daughter_two_ls), M.WELL_SIZE,
                     M.decay_reference_mass(name, row.lineshape), M.nominal_mass["Dst"], M.nominal_mass["D"]))
            else
                (M.nominal_vertex_matching_factor(M.vertex_l(row.root_two_ls), M.WELL_SIZE, M.nominal_mass["Bp"], m_r, M.nominal_mass["Dst"]),
                 M.nominal_vertex_matching_factor(M.vertex_l(row.daughter_two_ls), M.WELL_SIZE, m_r, M.nominal_mass["D"], M.nominal_mass["K"]))
            end
            plus = name in M.CPLUS_EXCLUDED_RESONANCES ? "absent" : @sprintf("%+d", M.magic_sign(name, :Cplus))
            @printf(io, "| %s | %s | %s | %+d | %s | %.6g | %.6g | %.6g | %.6g | %s |\n",
                M.chain_name(name, row), join(("`$k`" for k in row.coupling_keys), " x "),
                fmt_complex(row.coupling_value), M.magic_sign(name), plus, prod_norm, dec_norm,
                M.chain_lineshape_matching_factor(name, row.lineshape), 1 / M.chain_propagator_spin_norm(row),
                fmt_complex(row.coupling_value * row.matching_factor))
        end
        println(io, """

        ## Lineshape parameters (TF-PWA)

        | resonance | mass (GeV) | width (GeV) | theta0 | q0 (GeV) |
        |---|---|---|---|---|""")
        for name in M.all_resonance_names
            row = first(eachrow(M.resonance_chain_rows(name)))
            spec = M.lineshape_spec(row.lineshape)
            haskey(M.params, name * "_width") || continue
            theta0 = spec.mc_gamma === nothing ? "-" : @sprintf("%.6g", M.param_real(name * "_theta0"))
            q0 = spec.mc_gamma === nothing ? "-" :
                 @sprintf("%.6g", spec.adhoc_q0 ? M.bwr_ls_adhoc_q0(name) : M.bwr_ls_q0(name))
            @printf(io, "| %s | %.6g | %.6g | %s | %s |\n", name, M.nominal_mass[name], M.param_real(name * "_width"), theta0, q0)
        end
        nr = M.nr_exp_lineshape()
        @printf(io, "\nNR(0-)SPp: alpha = %.10g, beta = %.10g, m0 = %.6g GeV\n", real(nr.αβ), imag(nr.αβ), nr.m0)
    end
    return path
end

